#!/usr/bin/env node
// Generates every token consumer from docs/tokens.json, the single source of truth.
//   node tools/build-tokens.mjs          write outputs
//   node tools/build-tokens.mjs --check  exit 1 if any output is missing or stale (CI)
// Zero dependencies. Outputs: demo/tokens.css and dist/* (DTCG JSON, XAML, Rust, Slint, GDScript).
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(join(root, 'docs/tokens.json'), 'utf8'));
const revision = tokens.designRevision;
const generatedNote = `Generated by tools/build-tokens.mjs from docs/tokens.json (Tessel revision ${revision}). Do not edit.`;

const roles = Object.keys(tokens.color);
for (const theme of ['lightColor', 'highContrastColor']) {
  const missing = roles.filter(role => !(role in tokens[theme]));
  if (missing.length) throw new Error(`${theme} is missing roles: ${missing.join(', ')}`);
}
const kebab = name => ({ background: 'bg', foreground: 'fg' })[name] ?? name.replace(/[A-Z]/g, c => `-${c.toLowerCase()}`);
const version = tokens.version;
const themes = { dark: tokens.color, light: tokens.lightColor, highContrast: tokens.highContrastColor };

// OKLab mixing for accent tints. The CSS output uses color-mix(in oklab, ...) so both agree.
const toLinear = c => { const v = c / 255; return v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; };
const fromLinear = v => { const c = v <= 0.0031308 ? v * 12.92 : 1.055 * v ** (1 / 2.4) - 0.055; return Math.round(Math.min(1, Math.max(0, c)) * 255); };
function hexToOklab(hex) {
  const [r, g, b] = channels(hex).map(toLinear);
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  return [0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s, 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s, 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s];
}
function oklabToHex([L, a, b]) {
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const rgb = [4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s, -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s, -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s];
  return '#' + rgb.map(v => fromLinear(v).toString(16).padStart(2, '0')).join('').toUpperCase();
}
const tint = (accentHex, baseHex, percent) => {
  const [a, b] = [hexToOklab(accentHex), hexToOklab(baseHex)];
  return oklabToHex(a.map((v, i) => b[i] + (v - b[i]) * percent / 100));
};

const pascal = name => name[0].toUpperCase() + name.slice(1);
const screaming = name => name.replace(/[A-Z]/g, c => `_${c}`).toUpperCase();
const snake = name => name.replace(/[A-Z]/g, c => `_${c.toLowerCase()}`);
const channels = hex => hex.slice(1).match(/../g).map(c => Number.parseInt(c, 16));
const fontStack = list => list.map(f => (/\s/.test(f) ? `'${f}'` : f)).join(', ');
const accentRoles = ['accent', 'action', 'actionHover', 'actionPressed', 'selectionIndicator', 'focus'];
const accentPresets = Object.entries(tokens.appearanceAccents.presets)
  .filter(([id]) => id !== tokens.appearanceAccents.default);
for (const [id, preset] of accentPresets) {
  if (!/^[a-z]+$/.test(id)) throw new Error(`Invalid accent ID: ${id}`);
  for (const theme of ['dark', 'light']) {
    for (const role of accentRoles) {
      if (!/^#[\da-f]{6}$/i.test(preset[theme]?.[role] ?? '') ||
          !/^oklch\([\d.]+ [\d.]+ [\d.]+\)$/.test(preset.oklch?.[theme]?.[role] ?? '')) {
        throw new Error(`Invalid ${id} ${theme} ${role} token`);
      }
    }
  }
}

// Roles that defer to the user's system colors when the browser forces colors.
const forcedColors = {
  background: 'Canvas', surface: 'Canvas', raised: 'Canvas', selected: 'Canvas', selectedStrong: 'Canvas', hover: 'Canvas', pressed: 'Canvas',
  foreground: 'CanvasText', muted: 'CanvasText', border: 'ButtonBorder', accent: 'Highlight', accentForeground: 'HighlightText',
  action: 'ButtonFace', actionHover: 'ButtonFace', actionPressed: 'ButtonFace', actionForeground: 'ButtonText', progress: 'Highlight',
  info: 'CanvasText', warning: 'CanvasText', success: 'CanvasText', danger: 'CanvasText',
  infoFill: 'Canvas', warningFill: 'Canvas', successFill: 'Canvas', dangerFill: 'Canvas',
  disabledForeground: 'GrayText', disabledFill: 'Canvas', readOnlyFill: 'Canvas', textSelection: 'Highlight', findMatch: 'Mark', findMatchActive: 'Highlight',
  materialRim: 'CanvasText', materialShade: 'Canvas', surround: 'Canvas',
};

// ---------- demo/tokens.css ----------
function css() {
  const block = (palette, indent, extra) => [
    ...roles.map(role => `${indent}--${kebab(role)}: ${palette[role]};`),
    ...extra.map(line => `${indent}${line}`),
  ].join('\n');
  const themeExtras = (scheme, syntaxKey = scheme) => [
    `color-scheme: ${scheme === 'light' ? 'light' : 'dark'};`,
    `--material-shadow: ${tokens.material[scheme === 'light' ? 'light' : 'dark'].structuralShadow};`,
    ...Object.entries(tokens.syntax[syntaxKey === 'light' ? 'light' : 'dark']).map(([k, v]) => `--syntax-${kebab(k)}: ${v};`),
    ...Object.entries(tokens.elevation.levels).map(([k, v]) => `--elevation-${k}: ${v.shadow[scheme === 'light' ? 'light' : 'dark']};`),
    `--scrim: ${tokens.elevation.scrim[scheme === 'light' ? 'light' : 'dark']};`,
  ];
  const base = [
    `--font-body: ${fontStack(tokens.type.sans)};`,
    `--font-mono: ${fontStack(tokens.type.mono)};`,
    ...Object.entries(tokens.type.size).map(([k, v]) => `--font-size-${k}: ${v}px;`),
    ...Object.entries(tokens.type.lineHeight).map(([k, v]) => `--line-height-${k}: ${v};`),
    ...Object.entries(tokens.type.letterSpacing).filter(([k]) => k !== 'unit').map(([k, v]) => `--letter-spacing-${kebab(k)}: ${v}em;`),
    `--control-gap: ${tokens.space.controlGap}px;`,
    `--group-gap: ${tokens.space.relatedGroupGap[1]}px;`,
    `--section-gap: ${tokens.space.sectionGap}px;`,
    `--touch-target: ${tokens.density.touchControlMinWidth}px;`,
    `--motion-short: ${tokens.motion.shortTransition}ms;`,
    `--motion-panel: ${tokens.motion.panelTransition}ms;`,
    ...Object.entries(tokens.motion.duration).map(([k, v]) => `--motion-${k}: ${v}ms;`),
    ...Object.entries(tokens.motion.easing).map(([k, v]) => `--ease-${k}: cubic-bezier(${v.join(', ')});`),
    ...Object.entries(tokens.surfaceAliases).map(([alias, role]) => `--${alias}: var(--${kebab(role)});`),
    ...Object.entries(tokens.focusRing.styles).flatMap(([k, v]) => [`--focus-${k}-width: ${v.width}px;`, `--focus-${k}-offset: ${v.offset}px;`]),
    ...tokens.accentTint.roles.flatMap(role => tokens.accentTint.steps.map((step, i) =>
      `--${kebab(role)}-tint-${i + 1}: color-mix(in oklab, var(--${kebab(role)}) ${step}%, var(--${kebab(tokens.accentTint.over)}));`)),
  ];
  const scopes = (dark, light, indent) => [
    `${indent}:root {`,
    ...(indent ? [] : base.map(line => `  ${line}`)),
    block(dark, `${indent}  `, indent ? [] : themeExtras('dark')),
    `${indent}}`,
    `${indent}:root[data-theme=light] {`,
    block(light, `${indent}  `, indent ? [] : themeExtras('light')),
    `${indent}}`,
    `${indent}@media (prefers-color-scheme: light) {`,
    `${indent}  :root[data-theme=system] {`,
    block(light, `${indent}    `, indent ? [] : themeExtras('light')),
    `${indent}  }`,
    `${indent}}`,
  ].join('\n');
  function accentScopes(useOklch, indent = '') {
    return accentPresets.map(([id, preset]) => {
      const palette = useOklch ? preset.oklch : preset;
      const selector = `:root[data-accent=${id}]`;
      const declarations = theme => accentRoles.map(role => `--${kebab(role)}: ${palette[theme][role]};`).join(' ');
      return [
        `${indent}${selector} { ${declarations('dark')} }`,
        `${indent}${selector}[data-theme=light] { ${declarations('light')} }`,
        `${indent}@media (prefers-color-scheme: light) {`,
        `${indent}  ${selector}[data-theme=system] { ${declarations('light')} }`,
        `${indent}}`,
      ].join('\n');
    }).join('\n');
  }
  return [
    `/* ${generatedNote} */`,
    scopes(tokens.color, tokens.lightColor, ''),
    accentScopes(false),
    '',
    '@supports (color: oklch(0.5 0 0)) {',
    scopes(tokens.colorOklch.dark, tokens.colorOklch.light, '  '),
    accentScopes(true, '  '),
    '}',
    '',
    `:root[data-theme=high-contrast] {`,
    block(tokens.highContrastColor, '  ', themeExtras('dark')),
    `}`,
    '',
    '@media (forced-colors: active) {',
    `  :root { --selection-indicator: Highlight !important; --focus: Highlight !important; --grid: Canvas !important; --edge: CanvasText !important; ${Object.entries(forcedColors).map(([role, value]) => `--${kebab(role)}: ${value} !important;`).join(' ')} }`,
    '}',
    '',
  ].join('\n');
}

// ---------- dist/tessel.tokens.json (W3C DTCG 2025.10 format) ----------
function dtcg() {
  const color = hex => ({ $type: 'color', $value: { colorSpace: 'srgb', components: channels(hex).map(c => +(c / 255).toFixed(6)), alpha: 1, hex: hex.toLowerCase() } });
  const dim = px => ({ $type: 'dimension', $value: { value: px, unit: 'px' } });
  const ms = value => ({ $type: 'duration', $value: { value, unit: 'ms' } });
  const palette = p => Object.fromEntries(roles.map(role => [role, color(p[role])]));
  const presets = Object.fromEntries(accentPresets.map(([id, preset]) => [id,
    Object.fromEntries(['dark', 'light'].map(theme => [theme,
      Object.fromEntries(accentRoles.map(role => [role, color(preset[theme][role])]))]))]));
  const d = tokens.density;
  return JSON.stringify({
    $description: generatedNote,
    $version: version,
    color: { dark: palette(tokens.color), light: palette(tokens.lightColor), highContrast: palette(tokens.highContrastColor), accentPresets: presets },
    syntax: Object.fromEntries(['dark', 'light'].map(theme => [theme, Object.fromEntries(Object.entries(tokens.syntax[theme]).map(([k, v]) => [k, color(v)]))])),
    accentTint: Object.fromEntries(tokens.accentTint.roles.map(role => [role, Object.fromEntries(Object.entries(themes).map(([theme, p]) =>
      [theme, Object.fromEntries(tokens.accentTint.steps.map((step, i) => [`tint${i + 1}`, color(tint(p[role], p[tokens.accentTint.over], step))]))]))])),
    elevation: tokens.elevation,
    focusRing: tokens.focusRing, table: tokens.table, navigation: tokens.navigation, statusBar: tokens.statusBar, states: tokens.states,
    commandPalette: tokens.commandPalette, layouts: tokens.layouts, canvas: tokens.canvas, undo: tokens.undo, inlineFeedback: tokens.inlineFeedback,
    space: {
      ...Object.fromEntries(tokens.space.scale.map(v => [`s${v}`, dim(v)])),
      controlGap: dim(tokens.space.controlGap), controlGapMinimum: dim(tokens.space.controlGapMinimum),
      relatedGroupGap: dim(tokens.space.relatedGroupGap[1]), sectionGap: dim(tokens.space.sectionGap),
      compartmentGutter: dim(tokens.space.compartmentGutter),
    },
    density: Object.fromEntries(['compact', 'comfortable', 'touch'].map(mode => [mode, {
      panelPadding: dim(d[mode].panelPadding), controlMinHeight: dim(d[mode].controlMinHeight), rowMinHeight: dim(d[mode].rowMinHeight),
    }])),
    touchTarget: dim(d.touchControlMinWidth),
    font: {
      sans: { $type: 'fontFamily', $value: tokens.type.sans },
      mono: { $type: 'fontFamily', $value: tokens.type.mono },
      size: Object.fromEntries(Object.entries(tokens.type.size).map(([k, v]) => [k, dim(v)])),
      weight: Object.fromEntries(Object.entries(tokens.type.weight).map(([k, v]) => [k, { $type: 'fontWeight', $value: v }])),
      lineHeight: { $type: 'number', $value: tokens.type.bodyLineHeight, roles: Object.fromEntries(Object.entries(tokens.type.lineHeight).map(([k, v]) => [k, { $type: 'number', $value: v }])) },
      letterSpacing: Object.fromEntries(Object.entries(tokens.type.letterSpacing).filter(([k]) => k !== 'unit').map(([k, v]) => [k, { $type: 'dimension', $value: `${v}em` }])),
      densityRoles: tokens.type.densityRoles,
    },
    shortcuts: tokens.shortcuts,
    feedback: tokens.feedback,
    motion: { short: ms(tokens.motion.shortTransition), panel: ms(tokens.motion.panelTransition), maximum: ms(tokens.motion.maximumTransition), duration: Object.fromEntries(Object.entries(tokens.motion.duration).map(([k, v]) => [k, ms(v)])), easing: Object.fromEntries(Object.entries(tokens.motion.easing).map(([k, v]) => [k, { $type: 'cubicBezier', $value: v }])) },
    inspector: { width: dim(tokens.compartments.inspectorWidth), min: dim(tokens.compartments.inspectorMin), max: dim(tokens.compartments.inspectorMax) },
  }, null, 2) + '\n';
}

